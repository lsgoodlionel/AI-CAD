"""合理性阈值的**单一真相源**：每个数字都要有出处。

**为什么这么严**：本仓库有过先例 —— 凭记忆写的平法代号表混进了非平法代号、
比例表里有国标根本没有的 `1:75`。合理性分析会据此否定构件，一个记错的
数字会把真构件判成「不可能」，比不查更坏。

所以每条限值都是一个 `Limit`，必须带：
- `source`：规范号 + 条款号（如 `GB55008-2021 §4.4.2`），或 `EMPIRICAL`（工程量级
  经验区间，不是规范）、`PHYSICS`（物理常数/量纲）；
- `text`：**原文摘录**（规范类必填，逐字，从 `regulation_books.full_text` 取）；
- `note`：适用条件与已知例外。

**查不到就标 `UNVERIFIED`**，并写清查过什么。带 `UNVERIFIED` 的限值
只能用于 `suspect` 档，不得用来出 `impossible`/`implausible` 结论 ——
由 `tests/test_plausibility_codes.py` 强制。
"""
from __future__ import annotations

from dataclasses import dataclass

#: 非规范来源的三种出处标记
EMPIRICAL = "EMPIRICAL"          # 工程量级经验区间（本项目语料或通用工程经验）
PHYSICS = "PHYSICS"              # 物理常数与量纲关系
UNVERIFIED = "UNVERIFIED"        # 没能在知识库里找到出处


@dataclass(frozen=True)
class Limit:
    """一条限值。`value` 可以是数、区间 (lo, hi)，或按等级分档的 dict。"""
    key: str
    value: object
    unit: str
    source: str
    text: str = ""
    note: str = ""

    @property
    def verified(self) -> bool:
        """规范来源必须有原文；经验/物理来源必须写明理由（note）。"""
        if self.source.startswith(UNVERIFIED):
            return False
        if self.source in (EMPIRICAL, PHYSICS):
            return bool(self.note)
        return bool(self.text)


def limit(key: str) -> Limit:
    if key not in LIMITS:
        raise KeyError(f"未登记的限值 {key!r} —— 先登记出处再用")
    return LIMITS[key]


def value(key: str):
    return limit(key).value


def lower_bound(key: str) -> tuple[float, str]:
    """一条**下限型**限值 → (可比较的数值, 这个数取自哪一档)。

    规范把最小尺寸按构件形式分档（矩形柱 300 / 圆柱 350、现浇实心板 80 /
    叠合板预制底板 50、高层剪力墙 160 / 多层 140）。**而模型里没有这些区分** ——
    识别器只给出几何，分不出圆柱还是方柱、叠合还是现浇。

    所以下限检查一律取**最宽松的一档（最小值）**：只否定「低于任何一种允许情形」
    的构件。宁可少报，也不能拿高档限值去指控一个本可以合规的构件 ——
    这一层的结论会被拿去从算量里剔除构件，误判的代价比漏判大。

    返回的档位名要写进 `evidence`，否则读报告的人无从知道比的是哪个数。
    """
    limit_ = limit(key)
    value_ = limit_.value
    if isinstance(value_, dict):
        numeric = {k: float(v) for k, v in value_.items()
                   if isinstance(v, (int, float))}
        if not numeric:
            raise ValueError(f"限值 {key} 的分档里没有数值：{value_!r}")
        label = min(numeric, key=lambda k: numeric[k])
        return numeric[label], label
    return float(value_), ""          # type: ignore[arg-type]


def unverified_keys() -> tuple[str, ...]:
    return tuple(sorted(k for k, v in LIMITS.items() if not v.verified))


